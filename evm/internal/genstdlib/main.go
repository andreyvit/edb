package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	// strings.Builder writes cannot fail.
	var out strings.Builder
	_, _ = out.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage evm\n\n// standardSignature lists the fixed ABI of private virtual library leaves.\nfunc standardSignature(path,name string)(params,results []string,ok bool){\nswitch path+\".\"+name{\n")
	files, err := filepath.Glob("_stdlib/*.go")
	if err != nil {
		panic(err)
	}
	for _, path := range files {
		f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			panic(err)
		}
		for _, d := range f.Decls {
			fn, ok := d.(*ast.FuncDecl)
			if !ok || fn.Body != nil {
				continue
			}
			_, _ = fmt.Fprintf(&out, "case %q:\nreturn ", f.Name.Name+"."+fn.Name.Name)
			for j, fields := range []*ast.FieldList{fn.Type.Params, fn.Type.Results} {
				if j > 0 {
					_ = out.WriteByte(',')
				}
				_, _ = out.WriteString("[]string{")
				if fields != nil {
					for _, field := range fields.List {
						var b bytes.Buffer
						if err := format.Node(&b, token.NewFileSet(), field.Type); err != nil {
							panic(err)
						}
						n := max(1, len(field.Names))
						for i := 0; i < n; i++ {
							_, _ = fmt.Fprintf(&out, "%q,", b.String())
						}
					}
				}
				_, _ = out.WriteString("}")
			}
			_, _ = out.WriteString(",true\n")
		}
	}
	_, _ = out.WriteString("};return nil,nil,false\n}\n")
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("stdlib_signatures.go", formatted, 0644); err != nil {
		panic(err)
	}
}
