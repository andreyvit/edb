package evmbind

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"reflect"
	"sort"
	"strings"
)

// GenerateMethods emits MethodBindings for explicit registrations. Helpers must
// be exported package functions (not closures, method values, or generic instances).
// The output package must differ from each helper's package. Run this from a
// small go:generate program importing the registration list, then supply the
// result to RegisterMethods. Model and script names are not inferred from Go names.
func GenerateMethods(outputPackage string, methods []Method) ([]byte, error) {
	if !token.IsIdentifier(outputPackage) || outputPackage == "_" {
		return nil, fmt.Errorf("invalid output package %q", outputPackage)
	}
	funcs := map[string]methodFunction{}
	imports := map[string]string{}
	targets := map[string][2]string{}
	hasStringResult := false
	for _, m := range methods {
		f, err := describeMethod(m)
		if err != nil {
			return nil, err
		}
		at := strings.LastIndexByte(f.symbol, '.')
		if at < strings.LastIndexByte(f.symbol, '/') || at < 0 || !token.IsIdentifier(f.symbol[at+1:]) || !token.IsExported(f.symbol[at+1:]) {
			return nil, fmt.Errorf("evmbind: generation requires an exported package function: %s", f.symbol)
		}
		path, name := f.symbol[:at], f.symbol[at+1:]
		if strings.ContainsAny(path, "[]()") || strings.Contains(path[strings.LastIndexByte(path, '/')+1:], ".") {
			return nil, fmt.Errorf("evmbind: unsupported function %s", f.symbol)
		}
		targets[f.symbol] = [2]string{path, name}
		imports[path] = ""
		for i := 1; i < f.typ.NumIn(); i++ {
			t := f.typ.In(i)
			if t.PkgPath() != "" {
				if !token.IsExported(t.Name()) {
					return nil, fmt.Errorf("evmbind: unexported argument type %s", t)
				}
				imports[t.PkgPath()] = ""
			}
		}
		for i := 0; i < f.typ.NumOut(); i++ {
			hasStringResult = hasStringResult || f.typ.Out(i).Kind() == reflect.String
		}
		funcs[f.symbol] = f
	}
	var paths, names []string
	for p := range imports {
		paths = append(paths, p)
	}
	for n := range funcs {
		names = append(names, n)
	}
	sort.Strings(paths)
	sort.Strings(names)
	var b bytes.Buffer
	line := func(f string, args ...any) { fmt.Fprintf(&b, f+"\n", args...) }
	line("// Code generated by evmbind.GenerateMethods. DO NOT EDIT.\n//go:build !evmreflect\n\npackage %s", outputPackage)
	line("import (\"github.com/andreyvit/edb/evm/evmbind\"")
	if hasStringResult {
		line("%q", "strings")
	}
	if len(funcs) > 0 {
		line("\"github.com/andreyvit/edb/evm\";\"github.com/andreyvit/edb/kvo\";\"github.com/andreyvit/edb/values\"")
	}
	for i, p := range paths {
		if p == "github.com/andreyvit/edb/kvo" {
			imports[p] = "kvo"
			continue
		}
		imports[p] = fmt.Sprintf("api%d", i)
		line("%s %q", imports[p], p)
	}
	line(")")
	typeName := func(t reflect.Type) string {
		if t.PkgPath() != "" {
			return imports[t.PkgPath()] + "." + t.Name()
		}
		return t.String()
	}
	decode := func(t reflect.Type, v string) string {
		return scalarRead(t.Kind(), typeName(t), v)
	}
	encode := func(t reflect.Type, x string) string {
		if t.Kind() == reflect.String {
			return "values.String(strings.Clone(string(" + x + ")))"
		}
		return scalarWrite(t.Kind(), x)
	}
	line("var MethodBindings=evmbind.StaticMethods{")
	for _, name := range names {
		f := funcs[name]
		target := targets[name]
		callName := imports[target[0]] + "." + target[1]
		line("%q: {Signature:%q,", name, f.signature)
		line("Call:func(c *evm.Call)(err error){defer evmbind.Catch(%q,&err)", name)
		args := []string{"kvo.FromValue(c.Argument(0))"}
		for i := 1; i < f.typ.NumIn(); i++ {
			args = append(args, decode(f.typ.In(i), fmt.Sprintf("c.Argument(%d)", i)))
		}
		var results []string
		for i := 0; i < f.typ.NumOut(); i++ {
			results = append(results, fmt.Sprintf("r%d", i))
		}
		writeInvocation(line, callName, args, results)
		for i, r := range results {
			if f.typ.Out(i).Kind() == reflect.String {
				line("if err:=c.ChargeAllocation(uint64(len(%s)));err!=nil{return err}", r)
			}
			line("c.SetResult(%d,%s)", i, encode(f.typ.Out(i), r))
		}
		line("return nil},")
		if op := f.opcode(); op != 0 {
			line("Direct:evm.DirectBinding{Op:evm.%s,Call:func(c *evm.Call,x,y values.Value)(v values.Value,err error){defer evmbind.Catch(%q,&err)", "OpCallHost"+strings.ToUpper(strings.TrimPrefix(op.String(), "call.host.")), name)
			args = []string{"kvo.FromValue(x)"}
			if f.typ.NumIn() > 1 {
				args = append(args, decode(f.typ.In(1), "y"))
			}
			if f.typ.NumOut() > 0 {
				line("r:=%s(%s);return %s,nil", callName, strings.Join(args, ","), encode(f.typ.Out(0), "r"))
			} else {
				line("%s(%s);return values.Value{},nil", callName, strings.Join(args, ","))
			}
			line("}},")
		}
		line("},")
	}
	line("}")
	return format.Source(b.Bytes())
}
