package evmbind

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"io/fs"
	"reflect"
	"strings"

	"github.com/andreyvit/edb/nativebind"
	"github.com/andreyvit/edb/values"
)

// Generate emits direct Go conversions and method calls in a separate package.
func Generate(path, nativeImport, outputPackage string, files fs.FS) ([]byte, error) {
	s, err := parse(path, files)
	if err != nil {
		return nil, err
	}
	if !token.IsIdentifier(outputPackage) {
		return nil, fmt.Errorf("invalid output package %q", outputPackage)
	}
	var b bytes.Buffer
	line := func(pattern string, a ...any) { fmt.Fprintf(&b, pattern+"\n", a...) }
	line("// Code generated by evmbind. DO NOT EDIT.\n//go:build !evmreflect\n\npackage %s", outputPackage)
	line("import (")
	ns := sortedNodes(s)
	ids := map[*node]string{}
	hasAPI := false
	hasHost := false
	hasDirect := false
	for _, n := range ns {
		switch {
		case n.named:
			ids[n] = "Type" + n.name
		case n.inputOnly():
			ids[n] = n.kind.String()
		case n.kind == nodePointer:
			ids[n] = "Ptr" + n.elem.name
		default:
			ids[n] = "Scalar" + strings.ToUpper(n.name[:1]) + n.name[1:]
		}
		hasAPI = hasAPI || n.named
	}
	for _, op := range s.ops {
		hasHost = hasHost || op.recv == nil
		hasDirect = hasDirect || op.directOpcode() != 0
	}
	hasFields, hasPointers := false, false
	pointerElements := make(map[*node]bool)
	for _, n := range ns {
		hasFields = hasFields || n.kind == nodeStruct
		hasPointers = hasPointers || n.kind == nodePointer
		if n.kind == nodePointer {
			pointerElements[n.elem] = true
		}
	}
	if hasAPI {
		line("%q", "reflect")
	}
	if hasFields || hasPointers {
		line("%q", "unsafe")
	}
	if hasAPI || hasFields || hasPointers {
		line("")
	}
	if hasAPI {
		line("api %q", nativeImport)
	}
	line("%q", "github.com/andreyvit/edb/evm/evmbind")
	if hasFields {
		line("%q", "github.com/andreyvit/edb/nativebind")
	}

	if hasHost || hasDirect {
		line("%q", "github.com/andreyvit/edb/evm")
	}
	if len(ns) > 0 {
		line("%q", "github.com/andreyvit/edb/values")
	}
	line(")")
	typ := func(n *node) string {
		if n.named {
			return "api." + n.name
		}
		if n.kind == nodePointer {
			if !n.elem.named {
				return "*" + n.elem.name
			}
			return "*api." + n.elem.name
		}
		return n.name
	}
	for _, n := range ns {
		i := ids[n]
		line("func read%s(f *evmbind.Frame,v values.Value) %s {", i, typ(n))
		switch n.kind {
		case nodeStrings:
			line("return f.Strings(v)")
		case nodeJSONObject:
			line("return f.JSONObject(v)")
		case nodeCallback:
			line("return f.Callback(v)")
		case nodeStruct:
			line("return %s{", typ(n))
			for _, k := range n.fields {
				cell := fmt.Sprintf("evmbind.Field(v,%d,%t)", k.offset, k.t.shape.Aggregate())
				line("%s:read%s(f,%s),", k.name, ids[k.t], cell)
			}
			line("}")
		case nodePointer:
			line("if v.P==nil{return nil};if v.R==values.NativeAddress{return (%s)(v.P)};if old:=f.Object(%q,v.P);old!=nil{return old.(%s)};x:=new(%s);f.Remember(%q,v.P,x,func(){store%s(f,v,*x)});*x=read%s(f,evmbind.Field(v,0,%t));return x", typ(n), n.name, typ(n), typ(n.elem), n.name, ids[n.elem], ids[n.elem], n.elem.shape.Aggregate())
		case nodeInterface:
			line("if v==(values.Value{}){return nil};return f.DecodeInterface(v).(%s)", typ(n))
		default:
			line("return %s", scalarRead(nativeKind(n), typ(n), "v"))
		}
		line("}")
		if n.inputOnly() {
			continue
		}
		line("func write%s(f *evmbind.Frame,x %s) values.Value{", i, typ(n))
		switch n.kind {
		case nodeStruct:
			line("v:=values.Value{P:f.New(%d)};store%s(f,v,x);return v", n.shape.Cells, i)
		case nodePointer:
			line("if x==nil{return values.Value{}};if f!=nil {if p:=f.Origin(x);p!=nil{return values.Value{P:p}}};return values.Value{R:values.NativeAddress,P:unsafe.Pointer(x)}")
		case nodeInterface:
			line("return f.EncodeInterface(x)")
		case nodeString:
			line("return f.String(string(x))")
		default:
			line("return %s", scalarWrite(nativeKind(n), "x"))
		}
		line("}")
		if n.kind == nodeStruct {
			line("func store%s(f *evmbind.Frame,v values.Value,x %s){", i, typ(n))
			for _, k := range n.fields {
				if k.t.kind == nodeStruct {
					line("store%s(f,values.Value{P:values.CellAt(v.P,%d)},x.%s)", ids[k.t], k.offset, k.name)
				} else {
					line("*(*values.Value)(values.CellAt(v.P,%d))=write%s(f,x.%s)", k.offset, ids[k.t], k.name)
				}
			}
			line("}")
		} else if pointerElements[n] {
			line("func store%s(f *evmbind.Frame,v values.Value,x %s){*(*values.Value)(v.P)=write%s(f,x)}", i, typ(n), i)
		}
	}
	for _, n := range ns {
		if n.kind != nodeStruct {
			continue
		}
		var fields []nativebind.FieldSpec
		for _, f := range n.fields {
			fields = append(fields, nativebind.FieldSpec{Name: f.name, Type: typ(f.t), Kind: nativeKind(f.t)})
		}
		nativebind.GenerateFields(&b, "fields"+ids[n], typ(n), fields)
	}
	line("var Bindings = evmbind.Static{Fingerprint:%q,", s.fingerprint)
	if hasFields {
		line("Fields:map[string]*nativebind.GeneratedFields{")
		for _, n := range ns {
			if n.kind == nodeStruct {
				line("%q:&fields%s,", n.name, ids[n])
			}
		}
		line("},")
	}
	if hasAPI {
		line("Types:map[string]reflect.Type{")
		for _, n := range ns {
			if n.named {
				line("%q:reflect.TypeFor[%s](),", n.name, typ(n))
			}
		}
		line("},")
	}
	line("Calls:map[string]evmbind.Wrapper{")
	ops := append([]*operation{}, s.ops...)
	for _, n := range ns {
		ops = append(ops, n.methods...)
	}
	for _, op := range ops {
		line("%q:func(f *evmbind.Frame){", op.key)
		var params, results, args, lhs []string
		for i, n := range op.args {
			params = append(params, typ(n))
			idx := i
			if op.recv != nil {
				idx++
			}
			args = append(args, fmt.Sprintf("read%s(f,f.Argument(%d))", ids[n], idx))
		}
		for i, n := range op.outs {
			results = append(results, typ(n))
			lhs = append(lhs, fmt.Sprintf("r%d", i))
		}
		var recv string
		if op.recv == nil {
			params = append([]string{"*evm.Call"}, params...)
			args = append([]string{"f.Call"}, args...)
			recv = fmt.Sprintf("f.Host.(interface{%s(%s)(%s)})", op.name, strings.Join(params, ","), strings.Join(results, ","))
		} else if op.recv.kind == nodeInterface {
			recv = "f.Receiver.(" + typ(op.recv) + ")"
		} else {
			recv = fmt.Sprintf("read%s(f,f.Argument(0))", ids[op.recv])
		}
		writeInvocation(line, recv+"."+op.name, args, lhs)
		for i, n := range op.outs {
			line("f.SetResult(%d,write%s(f,r%d))", i, ids[n], i)
		}
		line("},")
	}
	if hasDirect {
		line("},")
		line("Direct: map[string]evmbind.DirectFactory{")
		for _, op := range s.ops {
			if op.directOpcode() != 0 {
				writeDirect(line, op, ids, typ)
			}
		}
	}
	line("}}")
	return format.Source(b.Bytes())
}
func Field(v values.Value, offset uint64, aggregate bool) values.Value {
	p := values.CellAt(v.P, offset)
	if aggregate {
		return values.Value{P: p}
	}
	if p == nil {
		return values.Value{}
	}
	return *(*values.Value)(p)
}

func nativeKind(n *node) reflect.Kind {
	switch n.shape.Kind {
	case values.BoolKind:
		return reflect.Bool
	case values.IntKind:
		switch n.kind {
		case nodeInt:
			return reflect.Int
		case nodeInt8:
			return reflect.Int8
		case nodeInt16:
			return reflect.Int16
		case nodeInt32:
			return reflect.Int32
		default:
			return reflect.Int64
		}
	case values.UintKind:
		switch n.kind {
		case nodeUint:
			return reflect.Uint
		case nodeUint8:
			return reflect.Uint8
		case nodeUint16:
			return reflect.Uint16
		case nodeUint32:
			return reflect.Uint32
		default:
			return reflect.Uint64
		}
	case values.FloatKind:
		if n.shape.Bits == 32 {
			return reflect.Float32
		}
		return reflect.Float64
	case values.StringKind:
		return reflect.String
	case values.PointerKind:
		return reflect.Pointer
	case values.StructKind:
		return reflect.Struct
	case values.SliceKind:
		return reflect.Slice
	case values.MapKind:
		return reflect.Map
	case values.InterfaceKind:
		return reflect.Interface
	default:
		panic("unsupported native field kind")
	}
}
