//go:build ignore

// Generate the floating-point loop's register forms from their expressions.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
)

type operation struct {
	name, mnemonic, expr string
	operands             string
}

// d is a raw destination. x, y and z are raw sources. A period is an
// instruction field with a fixed meaning, such as a slice or an index.
var ops = []operation{
	{"Add", "add", "x + y", "dxy"}, {"Sub", "sub", "x - y", "dxy"},
	{"Mul", "mul", "x * y", "dxy"}, {"Div", "div", "x / y", "dxy"},
	{"MulAdd", "mul.add", "float64(x*y) + z", "dxyz"},
	{"AddMul", "add.mul", "x + float64(y*z)", "dxyz"},
	{"SubAdd", "sub.add", "float64(x-y) + z", "dxyz"},
	{"Move", "move", "x", "dx"},
	{"FromInt", "float.i64", "float64(int64(math.Float64bits(x)))", "dx"},
	{"FromUint", "float.u64", "float64(math.Float64bits(x))", "dx"},
	{"Less", "lt", "x < y", ".xy"},
	{"LoadIndex", "load.index", "", "d.."}, {"StoreIndex", "store.index", "", "..x"},
	{"Spill", "store", "x", ".x"},
}

func main() {
	var b bytes.Buffer
	line := func(s string, args ...any) { fmt.Fprintf(&b, s+"\n", args...) }
	line("// Code generated by go generate. DO NOT EDIT.\npackage evm")
	line("import (\"math\"; \"unsafe\"; \"github.com/andreyvit/edb/values\")")
	line("const (")
	for i, o := range ops {
		line("float%s floatKind = %d", o.name, i+1)
	}
	line(")")
	line("var floatKinds = [...]struct{name,operands string; base uint16}{")
	base := 0
	for _, o := range ops {
		line("float%s:{%q,%q,%d},", o.name, o.mnemonic, o.operands, base)
		n := 1
		for _, c := range o.operands {
			if c != '.' {
				n *= 3
			}
		}
		base += n
	}
	line("}")
	line(`func (l *floatLoop) run(r []uint64, p []unsafe.Pointer, iterations int) (pc, spent int) {
		var f0, f1 float64
		if l.loadMask&1!=0 { f0=math.Float64frombits(r[l.slots[0]]) }
		if l.loadMask&2!=0 { f1=math.Float64frombits(r[l.slots[1]]) }
		pc=l.head
	outer:
		for range iterations {
			for _,s:=range l.steps {
				switch s.form {`)
	base = 0
	for _, o := range ops {
		n := 1
		for _, c := range o.operands {
			if c != '.' {
				n *= 3
			}
		}
		for form := 0; form < n; form++ {
			var loc [4]string
			digits := form
			var subst []string
			var suffix []string
			for i := len(o.operands) - 1; i >= 0; i-- {
				role := o.operands[i]
				if role == '.' {
					continue
				}
				l := digits % 3
				digits /= 3
				loc[i] = fmt.Sprintf("f%d", l)
				if l == 2 {
					loc[i] = fmt.Sprintf("math.Float64frombits(r[s.slot[%d]])", i)
				}
				if role != 'd' {
					subst = append(subst, string(role), loc[i])
				}
				suffix = append([]string{[]string{"f0", "f1", "r"}[l]}, suffix...)
			}
			line("case %d: // %s.%s", base+form, o.mnemonic, strings.Join(suffix, "."))
			val := strings.NewReplacer(subst...).Replace(o.expr)
			switch o.name {
			case "Move":
				if loc[0] == loc[1] {
					continue // both names already refer to the same scratch local
				}
			case "Less":
				line("test := %s; r[s.slot[0]]=boolWord(test); if test==l.escapeOnTrue {pc=l.exit;spent+=l.cost-1;break outer}", val)
				continue
			case "Spill":
				line("r[s.slot[0]]=math.Float64bits(%s)", val)
				continue
			case "StoreIndex":
				line("*(*values.Value)(values.CellAt(p[s.slot[0]],r[s.slot[1]]))=values.Value{R:math.Float64bits(%s)}", loc[2])
				continue
			case "LoadIndex":
				val = "math.Float64frombits((*values.Value)(values.CellAt(p[s.slot[1]],r[s.slot[2]])).R)"
			}
			if loc[0] == "f0" || loc[0] == "f1" {
				line("%s=%s", loc[0], val)
			} else {
				line("r[s.slot[0]]=math.Float64bits(%s)", val)
			}
		}
		base += n
	}
	line(`			}
			}
			spent+=l.cost
			r[l.counter]++
			x,y:=int64(r[l.counter]),int64(r[l.limit])
			if x>y || x==y && !l.inclusive {pc=l.latch+1;break}
		}
		if l.writeMask&1!=0 {r[l.slots[0]]=math.Float64bits(f0)}
		if l.writeMask&2!=0 {r[l.slots[1]]=math.Float64bits(f1)}
		return pc,spent
	}`)
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("floatloop_run.go", src, 0644); err != nil {
		panic(err)
	}
}
