package main

import (
	"bytes"
	"go/format"
	"os"
	"reflect"
	"strings"

	"github.com/andreyvit/edb/nativebind"
	"github.com/andreyvit/edb/nativebind/internal/fixture"
)

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by nativebind. DO NOT EDIT.\npackage fixture\nimport (\"reflect\";\"unsafe\";\"github.com/andreyvit/edb/values\";\"github.com/andreyvit/edb/nativebind\")\n")
	t := reflect.TypeFor[fixture.Row]()
	var fs []nativebind.FieldSpec
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if f.IsExported() {
			fs = append(fs, nativebind.FieldSpec{Name: f.Name, Type: strings.ReplaceAll(f.Type.String(), "fixture.", ""), Kind: f.Type.Kind()})
		}
	}
	nativebind.GenerateFields(&b, "Fields", "Row", fs)
	out, e := format.Source(b.Bytes())
	if e != nil {
		panic(e)
	}
	if e = os.WriteFile("fields_gen.go", out, 0644); e != nil {
		panic(e)
	}
}
